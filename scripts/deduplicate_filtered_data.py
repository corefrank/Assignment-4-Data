"""CS336 A4: deduplicate kept WET documents while preserving document metadata.

Input:  kept.jsonl generated by filter_wet_data.py
Output: deduped.jsonl, deduped.txt, summary.json

This orchestration script reuses YOUR cs336_data.deduplication implementations.
It does not copy an existing third-party solution.
"""
from __future__ import annotations

import argparse
import json
import tempfile
import time
from pathlib import Path

from cs336_data.deduplication import (
    exact_line_deduplication,
    minhash_deduplication,
)


def read_documents(jsonl_path: Path) -> list[dict]:
    documents = []
    with jsonl_path.open("r", encoding="utf-8") as source:
        for line_number, line in enumerate(source, 1):
            if not line.strip():
                continue
            try:
                item = json.loads(line)
            except json.JSONDecodeError as exc:
                raise ValueError(f"Invalid JSON at line {line_number}") from exc
            if not isinstance(item, dict) or not isinstance(item.get("text"), str):
                raise ValueError(f"Missing string 'text' at line {line_number}")
            documents.append({"url": item.get("url"), "text": item["text"]})
    return documents


def count_lines(text: str) -> int:
    return len(text.splitlines())


def main() -> None:
    parser = argparse.ArgumentParser(description="Exact-line + MinHash deduplication for WET kept.jsonl")
    parser.add_argument("input_jsonl", type=Path)
    parser.add_argument("--output-dir", required=True, type=Path)
    parser.add_argument("--num-hashes", type=int, default=100)
    parser.add_argument("--num-bands", type=int, default=10)
    parser.add_argument("--ngrams", type=int, default=5)
    parser.add_argument("--jaccard-threshold", type=float, default=0.8)
    parser.add_argument("--min-words-after-line-dedup", type=int, default=1)
    args = parser.parse_args()

    if not args.input_jsonl.is_file():
        parser.error(f"Input file not found: {args.input_jsonl}")
    if args.output_dir.exists() and (not args.output_dir.is_dir() or any(args.output_dir.iterdir())):
        parser.error("Output directory is non-empty or not a directory; use a fresh --output-dir")
    if args.min_words_after_line_dedup < 1:
        parser.error("--min-words-after-line-dedup must be >= 1")
    if args.num_hashes <= 0 or args.num_bands <= 0 or args.num_hashes % args.num_bands:
        parser.error("--num-hashes must be positive and divisible by --num-bands")

    started = time.perf_counter()
    documents = read_documents(args.input_jsonl)
    args.output_dir.mkdir(parents=True, exist_ok=True)

    # The existing assignment functions operate on files, so create one
    # temporary file per document. Filenames are stable and preserve URL mapping.
    final_documents = []
    total_lines_in = sum(count_lines(doc["text"]) for doc in documents)
    total_lines_after = 0
    after_line_docs = 0

    with tempfile.TemporaryDirectory(prefix="cs336-a4-dedup-") as tmp:
        tmp_root = Path(tmp)
        original_dir = tmp_root / "original"
        line_dir = tmp_root / "line_dedup"
        fuzzy_dir = tmp_root / "fuzzy_dedup"
        original_dir.mkdir()
        line_dir.mkdir()
        fuzzy_dir.mkdir()

        original_paths = []
        metadata = {}
        for index, doc in enumerate(documents):
            name = f"doc_{index:08d}.txt"
            path = original_dir / name
            # Preserve original newlines and avoid leaking JSONL formatting.
            with path.open("w", encoding="utf-8", newline="") as target:
                target.write(doc["text"])
            original_paths.append(path)
            metadata[name] = doc["url"]

        if original_paths:
            exact_line_deduplication(original_paths, line_dir)

        # Blank documents, or those that become too short after line deletion,
        # should not be sent to the MinHash stage.
        line_paths = []
        for original in original_paths:
            line_path = line_dir / original.name
            text = line_path.read_text(encoding="utf-8")
            total_lines_after += count_lines(text)
            if len(text.split()) >= args.min_words_after_line_dedup:
                line_paths.append(line_path)
        after_line_docs = len(line_paths)

        if line_paths:
            minhash_deduplication(
                input_files=line_paths,
                num_hashes=args.num_hashes,
                num_bands=args.num_bands,
                ngrams=args.ngrams,
                jaccard_threshold=args.jaccard_threshold,
                output_directory=fuzzy_dir,
            )

        for path in sorted(fuzzy_dir.glob("doc_*.txt")):
            text = path.read_text(encoding="utf-8")
            final_documents.append({"url": metadata[path.name], "text": text})

    jsonl_output = args.output_dir / "deduped.jsonl"
    text_output = args.output_dir / "deduped.txt"
    with (
        jsonl_output.open("w", encoding="utf-8") as jsonl_stream,
        text_output.open("w", encoding="utf-8") as text_stream,
    ):
        for doc in final_documents:
            jsonl_stream.write(json.dumps(doc, ensure_ascii=False) + "\n")
            text_stream.write(" ".join(doc["text"].split()) + "\n")

    summary = {
        "input_jsonl": str(args.input_jsonl),
        "documents_input": len(documents),
        "documents_after_line_dedup": after_line_docs,
        "documents_after_minhash": len(final_documents),
        "documents_removed_minhash": after_line_docs - len(final_documents),
        "lines_input": total_lines_in,
        "lines_after_exact_dedup": total_lines_after,
        "lines_removed_exact": total_lines_in - total_lines_after,
        "num_hashes": args.num_hashes,
        "num_bands": args.num_bands,
        "ngrams": args.ngrams,
        "jaccard_threshold": args.jaccard_threshold,
        "runtime_seconds": round(time.perf_counter() - started, 3),
    }
    (args.output_dir / "summary.json").write_text(
        json.dumps(summary, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(json.dumps(summary, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
